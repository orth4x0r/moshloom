//! Compiles this crate's WGSL shaders to SPIR-V at build time and writes them out as Rust
//! `&'static [u32]` constants, so the crate never reads a shader file at runtime and never
//! needs a shader compiler in a release build.
//!
//! mosh-shaders (Task 1.12) owns the visualizer shaders; these two are the renderer's own
//! full-screen vertex shader and the compositor fragment shader. The crate deliberately does
//! not depend on mosh-shaders: the app wires the two together.

use std::fmt::Write as _;
use std::path::Path;
use std::{env, fs};

/// (wgsl file, rust constant name)
const SHADERS: &[(&str, &str)] = &[
    ("fullscreen.vert.wgsl", "FULLSCREEN_VERT"),
    ("compositor.frag.wgsl", "COMPOSITOR_FRAG"),
    ("compositor_stack.frag.wgsl", "COMPOSITOR_STACK_FRAG"),
    (
        "compositor_stack_masked.frag.wgsl",
        "COMPOSITOR_STACK_MASKED_FRAG",
    ),
    // HAP (block-compressed) overlay video: YCoCg, straight or separate alpha (O-hap).
    ("overlay_hap.frag.wgsl", "OVERLAY_HAP_FRAG"),
];

fn compile(path: &Path) -> Vec<u32> {
    let source = fs::read_to_string(path).expect("read shader");
    let module = match naga::front::wgsl::parse_str(&source) {
        Ok(module) => module,
        Err(error) => panic!(
            "{}: {}",
            path.display(),
            error.emit_to_string_with_path(&source, &path.display().to_string())
        ),
    };
    let mut validator = naga::valid::Validator::new(
        naga::valid::ValidationFlags::all(),
        naga::valid::Capabilities::all(),
    );
    let info = match validator.validate(&module) {
        Ok(info) => info,
        Err(error) => panic!(
            "{}: {}",
            path.display(),
            error.emit_to_string_with_path(&source, &path.display().to_string())
        ),
    };
    let options = naga::back::spv::Options {
        lang_version: (1, 3),
        ..Default::default()
    };
    match naga::back::spv::write_vec(&module, &info, &options, None) {
        Ok(words) => words,
        Err(error) => panic!("{}: {error}", path.display()),
    }
}

fn main() {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let shader_dir = manifest_dir.join("src").join("shaders");
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR");

    let mut generated = String::from("// generated by build.rs from src/shaders/*.wgsl\n");
    for (file, constant) in SHADERS {
        println!("cargo:rerun-if-changed=src/shaders/{file}");
        let words = compile(&shader_dir.join(file));
        writeln!(generated, "pub const {constant}: &[u32] = &{words:?};").unwrap();
    }

    fs::write(Path::new(&out_dir).join("shaders_gen.rs"), generated).expect("write shaders_gen.rs");
}
