//! Compiles every `wgsl/*.wgsl` to SPIR-V and emits the table `spirv()` reads.
//!
//! A broken shader fails the build here rather than at a live show: this is the only place where a
//! shader is compiled without a fallback. The pipeline mirrors `src/runtime.rs` line for line
//! (same naga version, same options), because `tests/compile.rs` asserts that a runtime compile of
//! a file produces exactly the words committed by this build step.
//!
//! The uniform struct size is reflected out of naga as well, so a change to the WGSL struct that
//! does not match `LayerUniforms` fails a test instead of reading the wrong bytes on stage.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dir = manifest.join("wgsl");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut files: Vec<PathBuf> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e}; run node scripts/extract_wgsl.mjs", dir.display()))
        .map(|e| e.expect("directory entry").path())
        .filter(|p| p.extension().is_some_and(|x| x == "wgsl"))
        .collect();
    files.sort_by(|a, b| a.file_name().cmp(&b.file_name()));
    if files.is_empty() {
        panic!("{} has no .wgsl files; run node scripts/extract_wgsl.mjs", dir.display());
    }

    let mut out = String::new();
    out.push_str("// @generated by build.rs from wgsl/*.wgsl. Do not edit.\n");
    out.push_str("pub(crate) static MODULES: &[crate::Module] = &[\n");

    for path in &files {
        let name = path.file_stem().and_then(|s| s.to_str()).expect("utf-8 file name");
        let src = fs::read_to_string(path).expect("read wgsl");
        let Compiled { words, uniform_bytes, bindings } = compile(path, name, &src);

        writeln!(out, "    crate::Module {{").expect("write");
        writeln!(out, "        name: {name:?},").expect("write");
        writeln!(out, "        uniform_bytes: {},", uniform_bytes.map_or_else(|| "None".to_string(), |n| format!("Some({n})"))).expect("write");
        writeln!(out, "        bindings: &[").expect("write");
        for (group, binding, kind) in bindings {
            writeln!(
                out,
                "            crate::Binding {{ group: {group}, binding: {binding}, kind: crate::BindingKind::{kind} }},"
            )
            .expect("write");
        }
        writeln!(out, "        ],").expect("write");
        writeln!(out, "        spirv: &[").expect("write");
        for chunk in words.chunks(8) {
            out.push_str("            ");
            for w in chunk {
                write!(out, "0x{w:08x}, ").expect("write");
            }
            out.pop();
            out.push('\n');
        }
        writeln!(out, "        ],").expect("write");
        writeln!(out, "    }},").expect("write");
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("spirv.rs"), out).expect("write spirv.rs");
}

/// One module's translated output: SPIR-V, the uniform block size naga computed, and bind group 0
/// sorted by `(group, binding)`.
struct Compiled {
    words: Vec<u32>,
    uniform_bytes: Option<u32>,
    bindings: Vec<(u32, u32, &'static str)>,
}

/// Parse, validate and translate one module; reflected data comes back with the words.
fn compile(path: &Path, name: &str, src: &str) -> Compiled {
    let module = naga::front::wgsl::parse_str(src).unwrap_or_else(|e| {
        let at = e.location(src).map(|l| format!(" line {}:{}", l.line_number, l.line_position)).unwrap_or_default();
        panic!("{}: {}{at}", path.display(), e.message())
    });
    let mut validator = naga::valid::Validator::new(
        naga::valid::ValidationFlags::all(),
        naga::valid::Capabilities::empty(),
    );
    let info = validator
        .validate(&module)
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let words = naga::back::spv::write_vec(&module, &info, &options(), None)
        .unwrap_or_else(|e| panic!("{}: SPIR-V for {name}: {e}", path.display()));

    let mut uniform_bytes = None;
    let mut bindings = Vec::new();
    for (_, var) in module.global_variables.iter() {
        let Some(binding) = var.binding else { continue };
        let kind = match var.space {
            naga::AddressSpace::Uniform => {
                if let naga::TypeInner::Struct { span, .. } = module.types[var.ty].inner {
                    uniform_bytes = uniform_bytes.or(Some(span));
                }
                "Uniform"
            }
            naga::AddressSpace::Handle => match module.types[var.ty].inner {
                naga::TypeInner::Image { .. } => "Texture",
                naga::TypeInner::Sampler { .. } => "Sampler",
                _ => continue,
            },
            _ => continue,
        };
        bindings.push((binding.group, binding.binding, kind));
    }
    bindings.sort_unstable();
    Compiled { words, uniform_bytes, bindings }
}

/// Keep in sync with `src/runtime.rs::options`. Explicit flags, never `Options::default()`: the
/// default depends on `debug_assertions` inside naga, and a build script and a test are not
/// guaranteed to agree on that.
fn options() -> naga::back::spv::Options<'static> {
    naga::back::spv::Options {
        lang_version: (1, 3),
        flags: naga::back::spv::WriterFlags::ADJUST_COORDINATE_SPACE
            | naga::back::spv::WriterFlags::LABEL_VARYINGS
            | naga::back::spv::WriterFlags::CLAMP_FRAG_DEPTH,
        // No remapping: the WGSL `@group`/`@binding` numbers are the descriptor set and binding
        // the renderer uses, which is why `bindings()` hands them straight to `mosh-render`.
        fake_missing_bindings: true,
        ..Default::default()
    }
}
